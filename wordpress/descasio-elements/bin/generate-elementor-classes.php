<?php
/**
 * Regenerates includes/elementor/widgets.php: one small named class per element (Elementor needs a class per widget).
 * Run after adding or renaming an element:  php bin/generate-elementor-classes.php
 */

$dir   = dirname( __DIR__ );
$slugs = array_map( fn( $f ) => basename( $f, '.php' ), glob( $dir . '/elements/*.php' ) );
sort( $slugs );
$out = "<?php\n/**\n * Generated by bin/generate-elementor-classes.php. Do not edit by hand.\n *\n * @package DescasioElements\n */\n\ndefined( 'ABSPATH' ) || exit;\n\n";
foreach ( $slugs as $slug ) {
	$class = 'Descasio_EW_' . str_replace( ' ', '_', ucwords( str_replace( '_', ' ', $slug ) ) );
	$out  .= "class {$class} extends Descasio_Elementor_Widget { const SLUG = '{$slug}'; }\n";
}
$out .= "\nreturn array( " . implode( ', ', array_map( fn( $s ) => "'Descasio_EW_" . str_replace( ' ', '_', ucwords( str_replace( '_', ' ', $s ) ) ) . "'", $slugs ) ) . " );\n";
file_put_contents( $dir . '/includes/elementor/widgets.php', $out );
echo count( $slugs ) . " widget classes written\n";
